"""A hardware candidate must not silently compile uncommitted HAL source."""
import subprocess
import sys
from pathlib import Path

import pytest


@pytest.fixture
def hal_checkout(tmp_path):
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    (tmp_path / "driver.c").write_text("/* committed input */\n")
    subprocess.run(["git", "-C", str(tmp_path), "add", "driver.c"], check=True)
    subprocess.run(["git", "-C", str(tmp_path), "-c", "user.name=Test", "-c",
                    "user.email=test@example.invalid", "commit", "-qm", "fixture"], check=True)
    return tmp_path


def check(hal):
    script = Path(__file__).resolve().parents[1] / "scripts/sx1301_build_provenance.py"
    return subprocess.run([sys.executable, str(script), "check", str(hal)],
                          capture_output=True, text=True)


def test_clean_hal_is_accepted(hal_checkout):
    assert check(hal_checkout).returncode == 0


def test_modified_committed_hal_is_rejected(hal_checkout):
    (hal_checkout / "driver.c").write_text("/* uncommitted modification */\n")
    result = check(hal_checkout)
    assert result.returncode != 0
    assert "tracked files must be clean" in result.stderr


def test_untracked_even_ignored_hal_source_is_rejected(hal_checkout):
    (hal_checkout / ".git/info/exclude").write_text("extra.h\n")
    (hal_checkout / "extra.h").write_text("/* hidden source input */\n")
    result = check(hal_checkout)
    assert result.returncode != 0
    assert "extra.h" in result.stderr


def test_generated_hal_config_is_not_an_uncommitted_source_patch(hal_checkout):
    config = hal_checkout / "libloragw/inc/config.h"
    config.parent.mkdir(parents=True)
    config.write_text("/* generated by HAL Makefile */\n")
    assert check(hal_checkout).returncode == 0
